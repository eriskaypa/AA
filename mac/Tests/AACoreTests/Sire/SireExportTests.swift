    // TV: 12 §7.10 file name; §4.5 bytes
    @Test func fileNameAndBytes() {
        var c = DateComponents(); c.year = 2026; c.month = 9; c.day = 30; c.hour = 14; c.minute = 32
        var cal = Calendar(identifier: .gregorian); cal.timeZone = F.zone
        let d = cal.date(from: c)!
        #expect(SireExport.defaultFileName(mode: "Print Checklist", now: d, zone: F.zone) == "SIRE_Print_Checklist_20260930_1432.txt")
        let bytes = SireExport.fileData(F.build("Print Checklist"))
        #expect(!bytes.starts(with: [0xEF, 0xBB, 0xBF]))
        #expect(!bytes.contains(0x0D))
    }

    @MainActor @Test func snapshotFromState() {
        let s = SireState()
        s.setStatus(.checked, for: "2.1.10")
        s.questionStatuses["9.9.9"] = "2"
        s.toggleBookmark("2.1.2")
        s.tasks.append(SireTask(questionNumber: "2.1.2", text: "A"))
        let snap = SireSessionSnapshot(s)
        #expect(snap.status("2.1.10") == .checked && snap.status("9.9.9") == .checked)
        #expect(snap.count(of: .checked) == 1)                       // CountByStatus compares the raw text
        #expect(snap.isBookmarked("2.1.2") && snap.hasTasks("2.1.2") && !snap.hasTasks("2.1.10"))
    }
