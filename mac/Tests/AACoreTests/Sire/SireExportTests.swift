enum SireExportFixture {
    static let zone = TimeZone(identifier: "Europe/Athens")!
    static let now: Date = {
        var c = DateComponents(); c.year = 2026; c.month = 9; c.day = 29; c.hour = 14; c.minute = 5
        var cal = Calendar(identifier: .gregorian); cal.timeZone = zone
        return cal.date(from: c)!
    }()
    static func at(_ h: Int, _ m: Int) -> NetDateTime { NetDateTime(year: 2026, month: 9, day: 30, hour: h, minute: m, kind: .local) }
    static let session = SireSessionSnapshot(
        statuses: [("2.1.10", "Checked"), ("1.1.1", "InProgress")], bookmarks: ["2.1.2"], forExport: ["2.1.10"],
        tasks: [.init(questionNumber: "2.1.10", text: "Check log", isCompleted: true, createdAt: at(10, 0)),
                .init(questionNumber: "2.1.2", text: "Sight cert", isCompleted: false, createdAt: at(9, 0)),
                .init(questionNumber: "2.1.10", text: "Review plan", isCompleted: false, createdAt: at(9, 30))])
    static let filtered = [SireSynthetic.q2110, SireSynthetic.q111]

    static func build(_ mode: String, session: SireSessionSnapshot = session, identified: SireIdentifiedTasks = SireSynthetic.identified,
                      selected: Set<String> = []) -> String {
        SireExport.build(mode: mode, all: SireSynthetic.questions, session: session, identified: identified,
                         filtered: filtered, selected: selected, now: now, zone: zone)
    }

    /// The body between the header frame (5 lines) and the footer frame (blank + 3 lines).
    static func body(_ mode: String, session: SireSessionSnapshot = session, identified: SireIdentifiedTasks = SireSynthetic.identified,
                     selected: Set<String> = []) -> String {
        let text = build(mode, session: session, identified: identified, selected: selected)
        var lines = text.components(separatedBy: "\n")
        #expect(lines.last == "")
        lines.removeLast()
        let inner = lines[5..<(lines.count - 4)]
        return inner.joined(separator: "\n") + "\n"
    }
}

