    // TV: 12 §7.10 empty state
    @Test func emptyState() {
        let empty = SireSessionSnapshot()
        #expect(F.body("All Tasks", session: empty) == "  No tasks found.\n")
        #expect(F.body("Completed Tasks", session: empty) == "  No completed tasks found.\n")
        #expect(F.body("Pending Tasks", session: empty) == "  No pending tasks found.\n")
