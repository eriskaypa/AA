        let summary = F.body("Inspection Summary", session: empty)
        #expect(summary.hasPrefix("  Inspection Summary: 3 questions\n\n--- Q 1.1.1 [None] ---"))
        #expect(summary.contains("--- Q 2.1.2 [None] ---") && summary.contains("--- Q 2.1.10 [None] ---"))
